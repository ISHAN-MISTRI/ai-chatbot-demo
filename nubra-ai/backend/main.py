def _require_admin(request_token: str | None):
    admin_token = (os.getenv("ADMIN_TOKEN") or "").strip()
    if not admin_token:
        raise HTTPException(status_code=503, detail="ADMIN_TOKEN is not configured on the server.")
    if not request_token or request_token != admin_token:
        raise HTTPException(status_code=401, detail="Unauthorized.")

def _cors_origins():
    raw = (os.getenv("CORS_ORIGINS") or "").strip()
    if not raw:
        return ["*"]
    return [o.strip() for o in raw.split(",") if o.strip()]


app.add_middleware(
    CORSMiddleware,
    allow_origins=_cors_origins(),
    allow_credentials=False,  # cannot be True with wildcard origins; keep it cookie-free
    allow_methods=["*"],
    allow_headers=["*"],
)


_startup_lock = threading.Lock()


def _auto_ingest_pdfs_if_needed():
    """
    Production behavior:
    - PDFs are bundled in repo under /pdfs (not user-uploaded).
    - If the DB has no completed reports, ingest PDFs once.
    - Idempotent via SHA-256 hash stored on report docs.
    """
    with _startup_lock:
        _, db = get_database()
        completed_reports = db.reports.count_documents({"status": "completed"})
        if completed_reports > 0:
            logger.info("Startup ingestion skipped: completed reports already exist (%s).", completed_reports)
            return {"status": "skipped", "reason": "reports_exist", "completed_reports": completed_reports}

        pdf_dir = pathlib.Path(__file__).resolve().parent.parent / "pdfs"
        if not pdf_dir.exists():
            logger.warning("Startup ingestion skipped: pdf dir not found: %s", pdf_dir)
            return {"status": "skipped", "reason": "no_pdfs_dir", "pdf_dir": str(pdf_dir)}

        pdf_paths = sorted([p for p in pdf_dir.glob("*.pdf") if p.is_file()])
        if not pdf_paths:
            logger.warning("Startup ingestion skipped: no PDFs found in %s", pdf_dir)
            return {"status": "skipped", "reason": "no_pdfs_found", "pdf_dir": str(pdf_dir)}

        logger.info("Startup ingestion: found %s PDFs in %s", len(pdf_paths), pdf_dir)
        ingested = 0
        skipped = 0
        failed: list[dict] = []
        for p in pdf_paths:
            try:
                result = ingest_pdf_path(str(p))
                if result.get("skipped"):
                    skipped += 1
                else:
                    ingested += 1
            except Exception as exc:
                failed.append({"file": p.name, "error": str(exc)})
                logger.exception("Startup ingestion failed for %s", p.name)
        logger.info("Startup ingestion finished: ingested=%s skipped=%s failed=%s", ingested, skipped, len(failed))
        return {"status": "completed", "ingested": ingested, "skipped": skipped, "failed": failed}


def _start_ingest_in_background():
    def _runner():
        try:
            _auto_ingest_pdfs_if_needed()
        except Exception:
            logger.exception("Ingestion crashed unexpectedly.")

    threading.Thread(target=_runner, name="auto-ingest", daemon=True).start()


@app.post("/api/admin/ingest")
async def admin_ingest(token: str | None = None):
    """Start PDF ingestion in background (free-tier safe)."""
    _require_admin(token)
    _start_ingest_in_background()
    return {"status": "started"}


@app.on_event("startup")
async def _startup():
    ensure_indexes()
    # Critical for Render free tier:
    # - Bind the port fast so health checks pass
    # - Run ingestion in a background thread (best-effort)
    auto_ingest = (os.getenv("AUTO_INGEST_ON_STARTUP", "1") or "1").strip().lower() not in {"0", "false", "no"}
    if not auto_ingest:
        logger.info("Startup ingestion disabled via AUTO_INGEST_ON_STARTUP=0")
        return

    _start_ingest_in_background()


def openai_client() -> OpenAI:
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        raise RuntimeError("OPENAI_API_KEY is not set in backend/.env")
    return OpenAI(api_key=api_key)


def _serialize_report(doc):
    return {
        "company_ticker": doc.get("company_ticker", "UNKNOWN"),
        "company_name": doc.get("company_name", "UNKNOWN"),
        "quarter": doc.get("quarter", "UNKNOWN"),
        "report_type": doc.get("report_type", "UNKNOWN"),
        "original_filename": doc.get("original_filename", ""),
        "total_pages": doc.get("total_pages", 0),
        "total_chunks": doc.get("total_chunks", 0),
        "uploaded_at": doc.get("uploaded_at"),
        "status": doc.get("status", "unknown"),
        "last_processed_page": doc.get("last_processed_page", 0),
        "error": doc.get("error"),
    }


def _extract_section_snippet(chunk_text: str) -> str:
    for line in (chunk_text or "").splitlines():
        cleaned = " ".join(line.strip().split())
        if len(cleaned) >= 8:
            return cleaned[:140]
    return "General financial disclosure"


def _build_source_references(chunk_docs: List[dict]) -> List[str]:
    if not chunk_docs:
        return []

    _, db = get_database()
    report_ids = list({doc.get("report_id") for doc in chunk_docs if doc.get("report_id") is not None})
    report_name_map = {}
    if report_ids:
        for report in db.reports.find({"_id": {"$in": report_ids}}, {"original_filename": 1}):
            report_name_map[report["_id"]] = report.get("original_filename") or "Unknown PDF"

    unique_refs = []
    seen = set()
    for doc in chunk_docs:
        report_id = doc.get("report_id")
        filename = (
            doc.get("source_filename")
            or report_name_map.get(report_id)
            or "Unknown PDF"
        )
        page = doc.get("page_number") or "?"
        section = _extract_section_snippet(doc.get("chunk_text", ""))
        key = (filename, page, section)
        if key in seen:
            continue
        seen.add(key)
        unique_refs.append(f"{filename} | Page {page} | Section: {section}")
        if len(unique_refs) >= 8:
            break

    return unique_refs


@app.post("/api/upload")
async def upload_reports(
    files: List[UploadFile] | None = File(default=None),
    files_array: List[UploadFile] | None = File(default=None, alias="files[]"),
):
    all_files = (files or []) + (files_array or [])
    if not all_files:
        raise HTTPException(status_code=400, detail="No PDF files uploaded.")

    response_files = []
    for file in all_files:
        if not file.filename.lower().endswith(".pdf"):
            raise HTTPException(status_code=400, detail=f"{file.filename} is not a PDF file.")
        file_bytes = await file.read()
        try:
            result = ingest_pdf(file_bytes, file.filename)
            response_files.append(
                {
                    "filename": file.filename,
                    "status": "completed",
                    "ticker": result.get("company_ticker", "UNKNOWN"),
                    "quarter": result.get("quarter", "UNKNOWN"),
                    "total_chunks": result.get("total_chunks", 0),
                }
            )
        except Exception as exc:
            response_files.append(
                {
                    "filename": file.filename,
                    "status": "failed",
                    "error": str(exc),
                }
            )

    return {
        "message": f"Processed {len(response_files)} file(s)",
        "files": response_files,
    }


@app.post("/api/chat", response_model=ChatResponse)
async def chat(request: ChatRequest):
    try:
        chunks = retrieve_relevant_chunks(request.user_message, request.company_ticker, request.quarters)
        chunk_docs = retrieve_chunk_documents(
            request.user_message, request.company_ticker, request.quarters
        )
        user_prompt = (
            "Here is the extracted financial report data:\n\n"
            f"{chunks}\n\n"
            f"User question: {request.user_message}"
        )
        client = openai_client()
        completion = client.chat.completions.create(
            model="gpt-4o",
            max_tokens=4000,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
        )
        response_text = (completion.choices[0].message.content or "").strip()
        source_refs = _build_source_references(chunk_docs)
        if source_refs:
            reference_block = "\n".join(f"{idx}. {ref}" for idx, ref in enumerate(source_refs, start=1))
            response_text = f"{response_text}\n\n### Source References\n{reference_block}"
        usage = completion.usage
        tokens_used = (usage.prompt_tokens if usage else 0) + (
            usage.completion_tokens if usage else 0
        )

        _, db = get_database()
        db.chat_history.insert_many(
            [
                {
                    "session_id": request.session_id,
                    "role": "user",
                    "content": request.user_message,
                    "company_ticker": request.company_ticker.upper(),
                    "quarters": request.quarters,
                    "created_at": utc_now(),
                },
                {
                    "session_id": request.session_id,
                    "role": "assistant",
                    "content": response_text,
                    "company_ticker": request.company_ticker.upper(),
                    "quarters": request.quarters,
                    "tokens_used": tokens_used,
                    "created_at": utc_now(),
                },
            ]
        )

        return ChatResponse(
            response=response_text,
            chunks_used=len(chunk_docs),
            tokens_used=tokens_used,
        )
    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc)) from exc


@app.post("/api/chat/stream")
async def chat_stream(request: ChatRequest):
    try:
        chunks = retrieve_relevant_chunks(request.user_message, request.company_ticker, request.quarters)
        chunk_docs = retrieve_chunk_documents(request.user_message, request.company_ticker, request.quarters)
    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc)) from exc
    source_refs = _build_source_references(chunk_docs)
    user_prompt = (
        "Here is the extracted financial report data:\n\n"
        f"{chunks}\n\n"
        f"User question: {request.user_message}"
    )
    client = openai_client()

    def event_stream():
        final_text_parts = []
        stream = client.chat.completions.create(
            model="gpt-4o",
            max_tokens=6000,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            stream=True,
        )
        for event in stream:
            delta = event.choices[0].delta.content if event.choices else None
            if delta:
                final_text_parts.append(delta)
                yield f"data: {json.dumps(delta)}\n\n"
        final_text = "".join(final_text_parts).strip()
        if final_text and source_refs:
            reference_block = "\n".join(f"{idx}. {ref}" for idx, ref in enumerate(source_refs, start=1))
            final_text = f"{final_text}\n\n### Source References\n{reference_block}"
            yield f"data: {json.dumps(f'\n\n### Source References\n{reference_block}')}\n\n"
        if final_text:
            _, db = get_database()
            db.chat_history.insert_many(
                [
                    {
                        "session_id": request.session_id,
                        "role": "user",
                        "content": request.user_message,
                        "company_ticker": request.company_ticker.upper(),
                        "quarters": request.quarters,
                        "created_at": utc_now(),
                    },
                    {
                        "session_id": request.session_id,
                        "role": "assistant",
                        "content": final_text,
                        "company_ticker": request.company_ticker.upper(),
                        "quarters": request.quarters,
                        "created_at": utc_now(),
                    },
                ]
            )
        yield "data: [DONE]\n\n"

    return StreamingResponse(event_stream(), media_type="text/event-stream")


