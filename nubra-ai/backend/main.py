@app.delete("/api/reports/{ticker}/{quarter}")
async def delete_report(ticker: str, quarter: str):
    _, db = get_database()
    doc = db.reports.find_one({"company_ticker": ticker.upper(), "quarter": quarter})
    if not doc:
        raise HTTPException(status_code=404, detail="Report not found.")

    db.extracted_json.delete_many({"report_id": doc["_id"]})
    db.embeddings.delete_many({"report_id": doc["_id"]})
    if doc.get("gridfs_file_id"):
        fs = get_gridfs(db)
        try:
            fs.delete(doc["gridfs_file_id"])
        except Exception:
            pass
    db.reports.delete_one({"_id": doc["_id"]})
    return {"message": f"Deleted report for {ticker.upper()} {quarter}"}


